"""Persona/paraphrase variants of seed scenarios. Generated once and committed."""

import hashlib
import json
import re
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from examiner.scenarios.schema import PACKS_DIR, Scenario, load_pack

Paraphraser = Callable[[list[str], str], Awaitable[list[str]]]

PERSONAS = [
    "a stressed customer typing fast on a phone: lowercase, short, a typo or two",
    "a retiree who writes formally and politely in full sentences",
    "a college student writing casually",
    "a non-native English speaker using simple, slightly unusual phrasing",
    "an annoyed customer who complains briefly before asking",
    "a small-business owner in a hurry who gets straight to the point",
]

PARAPHRASE_MODEL = "claude-haiku-5-5"


def persona_for(seed_id: str) -> str:
    digest = hashlib.sha256(seed_id.encode()).digest()
    return PERSONAS[digest[0] % len(PERSONAS)]


def _tokens(turns: list[str]) -> set[str]:
    return set(re.findall(r"[a-z0-9$%]+", " ".join(turns).lower()))


def is_duplicate(a: list[str], b: list[str], threshold: float = 0.85) -> bool:
    ta, tb = _tokens(a), _tokens(b)
    if not ta or not tb:
        return ta == tb
    return len(ta & tb) / len(ta | tb) > threshold


def make_variant(seed: Scenario, n: int, persona: str, turns: list[str]) -> Scenario:
    return seed.model_copy(
        update={"id": f"{seed.id}--v{n}", "seed_id": seed.id, "persona": persona, "turns": turns}
    )


@dataclass
class VariantReport:
    written: int = 0
    skipped: int = 0
    failed: list[str] = field(default_factory=list)


async def generate_variants(
    pack: str, paraphraser: Paraphraser, root: Path = PACKS_DIR, n: int = 1
) -> VariantReport:
    out_dir = root / pack / "variants"
    out_dir.mkdir(parents=True, exist_ok=True)
    report = VariantReport()
    for seed in (s for s in load_pack(pack, root=root) if s.seed_id is None):
        path = out_dir / f"{seed.id}--v{n}.yaml"
        if path.exists():
            report.skipped += 1
            continue
        start = PERSONAS.index(persona_for(seed.id))
        turns, persona = None, PERSONAS[start]
        for attempt in range(2):  # a retry switches persona: some barely change the wording
            persona = PERSONAS[(start + attempt) % len(PERSONAS)]
            candidate = await paraphraser(seed.turns, persona)
            if len(candidate) == len(seed.turns) and not is_duplicate(candidate, seed.turns):
                turns = candidate
                break
        if turns is None:
            report.failed.append(seed.id)
            continue
        variant = make_variant(seed, n, persona, turns)
        data = variant.model_dump(exclude_none=True)
        path.write_text(yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100))
        report.written += 1
    return report


PARAPHRASE_PROMPT = """Rewrite a bank customer's chat messages as if written by {persona}.

Rules:
- Keep exactly the same question and meaning in each message.
- Do not add or remove facts, amounts, dates, or timeframes.
- Do not answer the question.
- Return exactly {n} message(s), in order, as a JSON array of strings and nothing else.

Messages:
{messages}"""


def anthropic_paraphraser() -> Paraphraser:
    from anthropic import AsyncAnthropic

    client = AsyncAnthropic()

    async def paraphrase(turns: list[str], persona: str) -> list[str]:
        msg = await client.messages.create(
            model=PARAPHRASE_MODEL,
            max_tokens=1000,
            messages=[
                {
                    "role": "user",
                    "content": PARAPHRASE_PROMPT.format(
                        persona=persona, n=len(turns), messages=json.dumps(turns, indent=1)
                    ),
                }
            ],
        )
        text = "".join(b.text for b in msg.content if b.type == "text")
        match = re.search(r"\[.*\]", text, re.S)
        try:
            out = json.loads(match.group(0)) if match else []
        except json.JSONDecodeError:
            return []
        return [str(t) for t in out] if isinstance(out, list) else []

    return paraphrase


def render_index(pack: str, root: Path = PACKS_DIR) -> str:
    scenarios = load_pack(pack, root=root)
    variants: dict[str, int] = {}
    for s in scenarios:
        if s.seed_id:
            variants[s.seed_id] = variants.get(s.seed_id, 0) + 1
    seeds = [s for s in scenarios if s.seed_id is None]
    lines = [
        f"# Scenario pack `{pack}`",
        "",
        f"{len(seeds)} seeds, {len(scenarios)} scenarios in total. Generated by "
        f"`examiner index --pack {pack}`; do not edit by hand.",
        "",
        "| Seed | Area | Turns | Question | Citations | Variants |",
        "|---|---|---|---|---|---|",
    ]
    for s in seeds:
        q = s.turns[-1].replace("|", "\\|")
        lines.append(
            f"| {s.id} | {s.area} | {len(s.turns)} | {q} | {s.citation_display} | "
            f"{variants.get(s.id, 0)} |"
        )
    return "\n".join(lines) + "\n"
